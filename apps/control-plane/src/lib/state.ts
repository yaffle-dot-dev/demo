// Yaffle-Injected Variables
// =============================================================================

/**
 * Write a yaffle_injected_variables.tf that declares Yaffle-injected variables
 * (environment, is_preview) if they're not already declared in the workspace.
 * This prevents "undeclared variable" errors when Yaffle passes these vars.
 *
 * NOTE: We use "yaffle_injected_variables.tf" not "*_override.tf" because
 * Terraform override files can only modify existing declarations, not add new ones.
 */
export async function configureVariablesOverride(
  tfWorkDir: string,
): Promise<void> {
  const variablesToInject = [
    { name: "environment", type: "string", description: "Environment name (injected by Yaffle)" },
    { name: "is_preview", type: "bool", description: "Whether this is a preview environment (injected by Yaffle)" },
  ]

  // Check which variables are already declared by scanning .tf files
  const declaredVars = await findDeclaredVariables(tfWorkDir)

  const missingVars = variablesToInject.filter((v) => !declaredVars.has(v.name))

  if (missingVars.length === 0) {
    logger.debug("all yaffle variables already declared, skipping override", {
      "variables.declared": Array.from(declaredVars).join(", "),
    })
    return
  }

  // Generate HCL for missing variables
  const varBlocks = missingVars
    .map(
      (v) => `variable "${v.name}" {
  type        = ${v.type}
  description = "${v.description}"
}`,
    )
    .join("\n\n")

  const suffix = Math.random().toString(36).substring(2, 10)
  const overridePath = join(tfWorkDir, `yaffle_injected_variables_${suffix}.tf`)
  const overrideContent = `# Generated by Yaffle -- do not edit
# These variables are injected by Yaffle if not declared in the workspace.

${varBlocks}
`

  await writeFile(overridePath, overrideContent)
  logger.info(`variables override written: ${overridePath}`, {
    "variables.override_path": overridePath,
    "variables.injected": missingVars.map((v) => v.name).join(", "),
  })
}

/**
 * Scan .tf files in a directory for declared variables.
 * Returns a Set of variable names.
 */
async function findDeclaredVariables(tfWorkDir: string): Promise<Set<string>> {
  const declared = new Set<string>()
  const { readdir } = await import("node:fs/promises")

  let files: string[]
  try {
    files = await readdir(tfWorkDir)
  } catch {
    return declared
  }

  const tfFiles = files.filter((f) => f.endsWith(".tf") && !f.endsWith("_override.tf"))

  for (const file of tfFiles) {
    try {
      const content = await readFile(join(tfWorkDir, file), "utf-8")
      // Match `variable "name"` declarations
      const matches = content.matchAll(/variable\s+"([^"]+)"/g)
      for (const match of matches) {
        declared.add(match[1])
      }
    } catch {
      // Ignore read errors
    }
  }

  return declared
}
